type I18nValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (value: string) => string;
};

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => {
    const saved = window.localStorage.getItem(STORAGE_KEY);
    return saved === "mr" || saved === "hi" ? saved : "en";
  });
  const setLocale = (next: Locale) => {
    setLocaleState(next);
    window.localStorage.setItem(STORAGE_KEY, next);
  };
  useEffect(() => {
    document.documentElement.lang = locale === "mr" ? "mr-IN" : locale === "hi" ? "hi-IN" : "en";
    document.title = translateString("AI-Powered Port Management System", locale);
    const description = document.querySelector<HTMLMetaElement>('meta[name="description"]');
    if (description) description.content = translateString("Secure port management, document intelligence, and evidence-grounded workflow.", locale);
    const ogTitle = document.querySelector<HTMLMetaElement>('meta[property="og:title"]');
    if (ogTitle) ogTitle.content = translateString("AI-Powered Port Management System", locale);
    const ogDescription = document.querySelector<HTMLMetaElement>('meta[property="og:description"]');
    if (ogDescription) ogDescription.content = translateString("Port operations, evidence-grounded document intelligence, and governed workflow in one local-first system.", locale);
    const root = document.getElementById("root");
    if (!root) return;
    let applying = false;
    let observer: MutationObserver;
    const translateTextNode = (text: Text) => {
      const parent = text.parentElement;
      if (!parent || parent.closest("script,style,pre,code,.markdown-content,[data-no-translate]")) return;
      const current = text.nodeValue || "";
      let record = originalText.get(text);
      if (!record) record = { source: current, rendered: current };
      else if (current !== record.rendered && current !== record.source) record.source = current;
      const next = translateString(record.source, locale);
      record.rendered = next;
      originalText.set(text, record);
      if (current !== next) text.nodeValue = next;
    };
    const translateElement = (element: HTMLElement) => {
      if (element.closest("script,style,pre,code,.markdown-content,[data-no-translate]")) return;
      const records = originalAttributes.get(element) || new Map<string, { source: string; rendered: string }>();
      for (const attr of ["aria-label", "placeholder", "title"]) {
        const current = element.getAttribute(attr);
        if (current === null) continue;
        let record = records.get(attr);
        if (!record) record = { source: current, rendered: current };
        else if (current !== record.rendered && current !== record.source) record.source = current;
        const next = translateString(record.source, locale);
        record.rendered = next;
        records.set(attr, record);
        if (current !== next) element.setAttribute(attr, next);
      }
      originalAttributes.set(element, records);
    };
    const apply = () => {
      if (applying) return;
      applying = true;
      observer?.disconnect();
      const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
      let node: Node | null;
      while ((node = walker.nextNode())) {
        translateTextNode(node as Text);
      }
      root.querySelectorAll<HTMLElement>("*").forEach(translateElement);
      const skipLink = document.querySelector<HTMLElement>(".skip-link");
      if (skipLink) {
        if (skipLink.firstChild?.nodeType === Node.TEXT_NODE) translateTextNode(skipLink.firstChild as Text);
        translateElement(skipLink);
      }
      applying = false;
      const attrs = ["aria-label", "placeholder", "title"];
      observer.observe(root, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: attrs });
    };
    observer = new MutationObserver(() => apply());
    apply();
    return () => observer.disconnect();
  }, [locale]);
  const value = useMemo<I18nValue>(() => ({ locale, setLocale, t: (text) => translateString(text, locale) }), [locale]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used inside I18nProvider");
  return context;
}
